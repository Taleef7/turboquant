"""Regenerate the verified native-WSL CUDA runtime lock atomically."""

from __future__ import annotations

import os
import platform
import subprocess
import sys
import tempfile
from pathlib import Path


CUDA_INDEX_URL = "https://download.pytorch.org/whl/cu128"
PYPI_INDEX_URL = "https://pypi.org/simple"
DEV_ONLY_DISTRIBUTIONS = {
    "iniconfig",
    "mccabe",
    "platformdirs",
    "pluggy",
    "pygments",
    "pytest",
    "ruff",
    "tomli",
    "tomlkit",
}
LOCK_PATH = Path(__file__).resolve().parents[1] / "requirements" / "runtime.lock"


def _distribution_name(requirement: str) -> str:
    return requirement.split("==", maxsplit=1)[0].lower()


def _runtime_pins(freeze_output: str) -> list[str]:
    return [
        line
        for line in freeze_output.splitlines()
        if line and _distribution_name(line) not in DEV_ONLY_DISTRIBUTIONS
    ]


def _command_output(*command: str) -> str:
    return subprocess.check_output(command, text=True).strip()


def _lock_contents() -> str:
    freeze_output = _command_output(sys.executable, "-m", "pip", "freeze", "--all")
    pip_version = _command_output(sys.executable, "-m", "pip", "--version")
    header = [
        "# Generated by scripts/regenerate_runtime_lock.py; do not edit manually.",
        "# Regenerate exactly with the verified native-WSL CUDA environment:",
        f"# {sys.executable} scripts/regenerate_runtime_lock.py",
        f"# Generation interpreter: {sys.executable} (Python {platform.python_version()})",
        f"# Generation pip: {pip_version}",
        f"# PyTorch CUDA wheel index: {CUDA_INDEX_URL}",
        f"--index-url {CUDA_INDEX_URL}",
        f"--extra-index-url {PYPI_INDEX_URL}",
        "",
    ]
    return "\n".join([*header, *_runtime_pins(freeze_output), ""])


def main() -> None:
    if platform.system() != "Linux":
        raise SystemExit("Regenerate runtime.lock from the verified native WSL environment.")

    import torch

    if torch.version.cuda != "12.8" or not torch.cuda.is_available():
        raise SystemExit("Expected a working stable CUDA 12.8 PyTorch runtime.")

    contents = _lock_contents()
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=LOCK_PATH.parent, delete=False
    ) as temporary:
        temporary.write(contents)
        temporary_path = Path(temporary.name)
    try:
        os.replace(temporary_path, LOCK_PATH)
    finally:
        temporary_path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
